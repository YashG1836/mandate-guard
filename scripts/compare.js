#!/usr/bin/env node
// What does each layer of protection stop? Runs the benchmark's 50 out-of-limit tricks and 15 genuine
// purchases with the worst-case agent, switching on Mandate Guard's checks one layer at a time.
// Writes results/comparison.json and results/COMPARISON.md.
//
//   node scripts/compare.js
//
// This simulates simpler controls inside our own benchmark by turning checks off.
// It is not a test of any company's product.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import core from '../src/core.cjs';
import { buildScenarios, ALLOWANCE } from '../src/scenarios.js';
import { createEnv } from '../src/env.js';
import { runWorstCase } from '../src/agents/worstcase.js';
import { judge } from '../src/judge.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const fmt = (n) => core.formatINR(n);
const sum = (xs) => xs.reduce((a, b) => a + b, 0);

const LIMITS = core.LIMIT_CHECKS;
const PAYEE = [...LIMITS, 'payee_verified', 'merchant_allowed'];
const CART = [...PAYEE, 'cart_signed'];

// Each step adds one idea. The first four use a standing allowance; the last switches to a mandate for the task.
export const STAIRCASE = [
  { id: 'none', name: 'No protection', adds: 'The agent pays UPI directly.', guard: false, mandate: 'allowance' },
  { id: 'limits', name: 'Spending limits', adds: 'Caps each payment, the total and the number of payments.', enforce: LIMITS, mandate: 'allowance' },
  { id: 'payee', name: '+ Verified merchant', adds: 'Pays only verified merchants: no strangers, no lookalike UPI IDs.', enforce: PAYEE, mandate: 'allowance' },
  { id: 'cart', name: '+ Cart signed by the merchant', adds: 'Each payment must match a cart the merchant signed: right payee, exact amount, paid once.', enforce: CART, mandate: 'allowance' },
  { id: 'task', name: '+ Mandate for the task (Mandate Guard)', adds: 'The mandate is for this purchase only: its category, total and number of payments.', enforce: null, mandate: 'task' },
];

// The same layers, all with the demo's mandate for one task.
const TASK_LAYERS = [
  { id: 'limits', name: 'Spending limits', enforce: LIMITS, mandate: 'task' },
  { id: 'payee', name: '+ Verified merchant', enforce: PAYEE, mandate: 'task' },
  { id: 'cart', name: '+ Cart signed by the merchant', enforce: CART, mandate: 'task' },
  { id: 'all', name: 'All nine checks (Mandate Guard)', enforce: null, mandate: 'task' },
];

async function runLayer({ guard = true, mandate = 'task', enforce = null }) {
  const scenarios = buildScenarios();
  const rows = [];
  for (let i = 0; i < scenarios.length; i++) {
    const env = await createEnv(scenarios[i], { guard, index: i + 1, mandateStyle: mandate, enforce });
    await runWorstCase(env);
    rows.push(judge(env));
  }
  const atk = rows.filter((r) => r.kind === 'attack' && !r.within_mandate);
  const ben = rows.filter((r) => r.kind === 'benign');
  const through = {};
  for (const r of atk) if (r.attack_success) through[r.variant_name] = (through[r.variant_name] || 0) + 1;
  return {
    attacks: { runs: atk.length, through: atk.filter((r) => r.attack_success).length, misspent_inr: sum(atk.map((r) => r.misspent)), real_purchase_done: atk.filter((r) => r.goal_met).length },
    genuine: { runs: ben.length, done: ben.filter((r) => r.goal_met).length, blocked: sum(ben.map((r) => r.genuine_blocked)) },
    through_by_trick: through,
  };
}

export async function runComparison() {
  const staircase = [];
  for (const l of STAIRCASE) staircase.push({ id: l.id, name: l.name, adds: l.adds, mandate: l.mandate, checks: l.guard === false ? [] : l.enforce || core.CHECKS.map((c) => c.id), ...(await runLayer(l)) });
  const task = [];
  for (const l of TASK_LAYERS) task.push({ id: l.id, name: l.name, checks: l.enforce || core.CHECKS.map((c) => c.id), ...(await runLayer(l)) });
  return {
    meta: {
      generated_at: new Date().toISOString(),
      guard_version: core.GUARD_VERSION,
      agent: 'Worst-case agent (obeys every instruction it reads)',
      allowance: ALLOWANCE,
      note: "Simpler controls are simulated inside this benchmark by switching checks off. This is not a test of any company's product.",
    },
    staircase,
    task_mandate: task,
  };
}

function toMarkdown(c) {
  const a = c.meta.allowance;
  const L = [];
  L.push('# What each layer stops', '');
  L.push('Generated by `npm run compare`. The same 50 out-of-limit tricks and 15 genuine purchases as the main benchmark, with the worst-case agent (it obeys every instruction it reads). Mandate Guard\'s checks are switched on one layer at a time. Money is counted from the bank ledger.', '');
  L.push('Agent payments on UPI are being designed around limits the customer sets, for example [Pine Labs\' P3P](https://thepaypers.com/payments/news/pine-labs-launches-p3p-agentic-payment-protocol-on-upi) and NPCI\'s planned [Unified Agent Protocol](https://www.outlookbusiness.com/news/india-plans-ai-powered-upi-payments-framework-through-unified-agent-protocol). This shows what limits stop on their own, and what each idea in Mandate Guard adds.', '');
  L.push('| Layer | What it adds | Tricks that got through (of 50) | Money lost | Genuine purchases blocked (of 15) |');
  L.push('|---|---|---|---|---|');
  for (const s of c.staircase) L.push(`| ${s.name} | ${s.adds} | **${s.attacks.through}** | ${fmt(s.attacks.misspent_inr)} | ${s.genuine.blocked} |`);
  L.push('');
  L.push(`The first four rows use a standing allowance: ${fmt(a.per_payment_inr)} a payment, ${fmt(a.total_inr)} in all, up to ${a.max_payments} payments, any verified merchant, any category (the same limits as UPI Circle's full delegation). The last row uses a mandate for the one task, as in the demo.`, '');
  L.push('What still got through:', '');
  for (const s of c.staircase.slice(1)) {
    const t = Object.entries(s.through_by_trick).map(([k, n]) => `${k} (${n})`).join(', ');
    L.push(`- **${s.name}:** ${t || 'nothing'}`);
  }
  L.push('');
  L.push('## The same layers with a mandate for the task', '');
  L.push('| Layer | Tricks that got through (of 50) | Money lost | Genuine purchases blocked (of 15) |');
  L.push('|---|---|---|---|');
  for (const s of c.task_mandate) L.push(`| ${s.name} | **${s.attacks.through}** | ${fmt(s.attacks.misspent_inr)} | ${s.genuine.blocked} |`);
  L.push('');
  L.push(`**Note.** ${c.meta.note} Real systems may add checks of their own.`, '');
  return L.join('\n');
}

async function main() {
  const c = await runComparison();
  const dir = path.join(root, 'results');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'comparison.json'), JSON.stringify(c, null, 2));
  fs.writeFileSync(path.join(dir, 'COMPARISON.md'), toMarkdown(c));
  console.log('\nWhat each layer stops (50 out-of-limit tricks, worst-case agent)');
  for (const s of c.staircase) console.log(`  ${s.name.padEnd(40)} ${String(s.attacks.through).padStart(2)} of ${s.attacks.runs} got through   ${fmt(s.attacks.misspent_inr).padStart(10)} lost   ${s.genuine.blocked} genuine blocked`);
  console.log('\n  Wrote results/comparison.json and results/COMPARISON.md\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main().catch((e) => {
    console.error('\nError:', e.message);
    process.exit(1);
  });
}
